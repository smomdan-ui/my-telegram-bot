# --- Кнопки ---
def get_faq_keyboard():
    keyboard = [[KeyboardButton(text=question)] for question in FAQ.keys()]
    return ReplyKeyboardMarkup(keyboard=keyboard, resize_keyboard=True)

start_kb = ReplyKeyboardMarkup(keyboard=[[KeyboardButton(text="Далее")]], resize_keyboard=True)

# --- Хендлеры ---
@dp.message(commands=['start'])
async def start(message: types.Message):
    await message.answer(
        "Здравствуйте! 👋\n\n"
        "Я цифровой тьютор ВГАУ. С удовольствием помогу вам ответить на интересующие вас вопросы.\n\n"
        "Нажмите кнопку «Далее» для перехода к списку вопросов.",
        reply_markup=start_kb
    )

@dp.message()
async def handle_message(message: types.Message):
    if message.text == "Далее":
        await message.answer("Вот список часто задаваемых вопросов:", reply_markup=get_faq_keyboard())
    elif message.text in FAQ:
        await message.answer(FAQ[message.text])
    else:
        await message.answer("Извините, я не понимаю этот вопрос. Пожалуйста, выберите из списка.")

# --- Запуск бота ---
if __name__ == "__main__":
    asyncio.run(dp.start_polling(bot))
